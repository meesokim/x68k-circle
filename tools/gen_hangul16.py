#!/usr/bin/env python3
# Rasterize Hangul syllables and compatibility jamo to a 16x16 bitmap,
# plus a CP949 pair -> Unicode map, and write a zlib blob for the SDL picker.
#
# Needs Pillow and Noto Sans CJK KR (fonts-noto-cjk). Output is committed so
# a normal build does not need the font installed.

import os
import sys
import zlib

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "SDL", "hangul16_blob.inc")
FONT = "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc"
FONT_INDEX = 1  # Noto Sans CJK KR Regular
FONT_SIZE = 12
THRESHOLD = 90

SYL_FIRST = 0xAC00
SYL_COUNT = 11172  # U+AC00 .. U+D7A3
JAMO_FIRST = 0x3131
JAMO_COUNT = 0x318E - 0x3131 + 1  # compatibility jamo

CP949_LEAD0 = 0x81
CP949_LEADS = 0xFE - 0x81 + 1  # 126
CP949_TRAILS = 178


def trail_index(b):
    if 0x41 <= b <= 0x5A:
        return b - 0x41
    if 0x61 <= b <= 0x7A:
        return 26 + (b - 0x61)
    if 0x81 <= b <= 0xFE:
        return 52 + (b - 0x81)
    return -1


def raster(font, ch):
    img = Image.new("L", (16, 16), 0)
    draw = ImageDraw.Draw(img)
    b = font.getbbox(ch)
    w = b[2] - b[0]
    x = (16 - w) // 2 - b[0]
    draw.text((x, 0), ch, font=font, fill=255)
    px = img.load()
    out = bytearray(32)
    for y in range(16):
        bits = 0
        for col in range(16):
            if px[col, y] >= THRESHOLD:
                bits |= 0x8000 >> col
        out[y * 2] = (bits >> 8) & 0xFF
        out[y * 2 + 1] = bits & 0xFF
    return out


def build_cp949():
    table = bytearray(CP949_LEADS * CP949_TRAILS * 2)
    hangul = 0
    for lead in range(CP949_LEAD0, 0xFF):
        for trail in range(256):
            ti = trail_index(trail)
            if ti < 0:
                continue
            try:
                s = bytes([lead, trail]).decode("cp949")
            except UnicodeDecodeError:
                continue
            if len(s) != 1:
                continue
            cp = ord(s)
            if cp > 0xFFFF:
                continue
            slot = ((lead - CP949_LEAD0) * CP949_TRAILS + ti) * 2
            table[slot] = cp & 0xFF
            table[slot + 1] = (cp >> 8) & 0xFF
            if 0xAC00 <= cp <= 0xD7A3 or 0x3131 <= cp <= 0x318E:
                hangul += 1
    return table, hangul


def main():
    if not os.path.exists(FONT):
        print("font not found:", FONT, file=sys.stderr)
        return 1
    font = ImageFont.truetype(FONT, FONT_SIZE, index=FONT_INDEX)
    name = font.getname()
    print("font", name)

    bits = bytearray()
    for cp in range(SYL_FIRST, SYL_FIRST + SYL_COUNT):
        bits += raster(font, chr(cp))
    for cp in range(JAMO_FIRST, JAMO_FIRST + JAMO_COUNT):
        bits += raster(font, chr(cp))
    print("bitmaps", len(bits))

    cp949, hangul_pairs = build_cp949()
    print("cp949 map", len(cp949), "hangul/jamo pairs", hangul_pairs)

    # Sanity: CP949 B0 A1 is U+AC00 (가).
    ti = trail_index(0xA1)
    slot = ((0xB0 - CP949_LEAD0) * CP949_TRAILS + ti) * 2
    got = cp949[slot] | (cp949[slot + 1] << 8)
    if got != 0xAC00:
        print("CP949 check failed:", hex(got), file=sys.stderr)
        return 1

    raw = bytes(bits) + bytes(cp949)
    comp = zlib.compress(raw, 9)
    print("zlib", len(comp), "from", len(raw))

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/gen_hangul16.py — do not edit.\n")
        f.write("// 16x16 bitmaps from Noto Sans CJK KR (SIL Open Font License 1.1).\n")
        f.write("// Copyright 2014-2021 Adobe. https://github.com/notofonts/noto-cjk\n")
        f.write("static const unsigned kHangulGlyphs = %d;\n" % (SYL_COUNT + JAMO_COUNT))
        f.write("static const unsigned kCp949Leads = %d;\n" % CP949_LEADS)
        f.write("static const unsigned kCp949Trails = %d;\n" % CP949_TRAILS)
        f.write("static const unsigned char kHangulZlib[] = {\n")
        for i in range(0, len(comp), 16):
            chunk = comp[i:i + 16]
            f.write("    " + ",".join("0x%02x" % b for b in chunk) + ",\n")
        f.write("};\n")
        f.write("static const unsigned kHangulZlibSize = %d;\n" % len(comp))
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
